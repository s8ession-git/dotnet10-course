CREATE SCHEMA IF NOT EXISTS training;


-- drop table if exists training.departments cascade;
create table if not exists training.departments
(
	id bigint generated by default as identity primary key,
	name text not null
);

-- drop table if exists training.employees cascade;
create table if not exists training.employees
(
	id bigint generated by default as identity primary key,
	name text not null,
	department_id bigint not null,
	constraint fk_employees_department_id foreign key (department_id) references training.departments(id)
);

-- drop table if exists training.courses cascade;
create table if not exists training.courses
(
	id bigint generated by default as identity primary key,
	title text not null,
	price numeric(12, 2) not null
		check (price >= 0)
);

-- drop table if exists training.course_records cascade;
create table if not exists training.course_records
(
	course_id bigint not null,
	employee_id bigint not null,
	agreed_price numeric(12, 2) not null
		check (agreed_price >= 0),
	score int
		check (score >=0 and score <= 100),
	constraint pk_course_records
		primary key (course_id, employee_id),
	constraint fk_course_records_course_id
		foreign key (course_id) references training.courses(id),
	constraint fk_course_records_employee_id
		foreign key (employee_id) references training.employees(id)
);

